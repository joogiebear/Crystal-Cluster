// Writes store/app-store-connect.md: every id, name and description to type into App Store Connect,
// generated from the game's own data so the two can never drift apart.
// Run with: npm run store:metadata
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACHIEVEMENTS, LEADERBOARDS } from '../js/data.js';
import { PRODUCTS, productId } from '../js/cosmetics.js';
import { ACHIEVEMENT_PREFIX, LEADERBOARD_PREFIX } from '../js/native.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'capacitor.config.json'), 'utf8'));
const table = (head, rows) => [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const code = (s) => `\`${s}\``;
const points = ACHIEVEMENTS.reduce((sum, a) => sum + a.points, 0);

const out = `# App Store Connect reference

Generated by \`npm run store:metadata\`. Do not edit by hand: change the game data and run it again.

Bundle ID: ${code(config.appId)}

## In-App Purchases (${PRODUCTS.length})

Create these under Monetization > In-App Purchases. The product ID must match exactly.
Tips are **Consumable**; packs are **Non-Consumable**. Turn Family Sharing on for the packs if you like.

${table(
  ['Reference name', 'Product ID', 'Type', 'Price', 'Display name', 'Description'],
  PRODUCTS.map((p) => [p.name, code(productId(p.id)), p.kind === 'tip' ? 'Consumable' : 'Non-Consumable', p.price, p.name, p.kind === 'tip' ? 'A tip to support the game. Thank you!' : p.blurb])
)}

## Game Center achievements (${ACHIEVEMENTS.length}, ${points} of 1000 points)

Create these under Growth & Marketing > Game Center > Achievements. Hidden: No. Achievable more than once: No.
Use the same text for the pre-earned and earned descriptions. Images are in \`store/game-center/\`.

${table(
  ['Reference name / title', 'Achievement ID', 'Points', 'Description', 'Image'],
  ACHIEVEMENTS.map((a) => [a.name, code(ACHIEVEMENT_PREFIX + a.id), a.points, a.desc, code(`achievement-${a.id}.jpg`)])
)}

## Game Center leaderboards (${LEADERBOARDS.length})

Create these under Game Center > Leaderboards as **Classic** leaderboards. Score submission type: Best Score.

${table(
  ['Reference name / title', 'Leaderboard ID', 'Score format and sort', 'What it ranks'],
  LEADERBOARDS.map((b) => [b.name, code(LEADERBOARD_PREFIX + b.id), b.format, b.desc])
)}
`;
fs.writeFileSync(path.join(root, 'store', 'app-store-connect.md'), out);
console.log('wrote store/app-store-connect.md');
